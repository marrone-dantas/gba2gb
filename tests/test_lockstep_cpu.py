"""Phase 0 lockstep test: each kernel runs on Unicorn (ARM7 Thumb, reference)
and on headless PyBoy (SM83 ROM generated by gba2gbc-core) with the same seeds
in R0-R3; R0 must match bit for bit (HRAM $FF80-$FF83).

Seeds per kernel: LOCKSTEP_SEEDS environment variable (default 1000).
SM83 cycles measured by the runtime timer are written to build/cycles.csv."""
import os
import subprocess
import glob
import pytest
from tools.profile.seeds import seeds as _seeds
from tools.harness import RefARM, GB

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KDIR = os.path.join(ROOT, "tests", "kernels")
BUILD = os.path.join(ROOT, "build")
SEEDS = int(os.environ.get("LOCKSTEP_SEEDS", "1000"))
from tools.harness import SP0, SENTINEL  # noqa: F401
KERNELS = sorted(os.path.basename(p)[:-2] for p in glob.glob(os.path.join(KDIR, "k*.c")))


@pytest.fixture(scope="session", autouse=True)
def build_kernels():
    subprocess.run(["make", "-s", "-C", KDIR], check=True)
    os.makedirs(os.path.join(BUILD, "roms"), exist_ok=True)
    yield


def seeds(name):
    return _seeds(name, SEEDS)


MODES = ["phase0", "sound", "profile", "aapcs"]


def profile_for(elf):
    from tools.profile.range_tracer import trace_kernel
    name = os.path.basename(elf)[:-4]
    p = os.path.join(BUILD, "profiles", name + ".json")
    import json
    if os.path.exists(p) and os.path.getmtime(p) >= os.path.getmtime(elf):
        prof = json.load(open(p))
        if prof.get("seeds") == SEEDS:  # a profile from another seed count is not reused
            return prof
    return trace_kernel(elf, SEEDS, p)


@pytest.mark.parametrize("mode", MODES)
@pytest.mark.parametrize("kernel", KERNELS)
def test_lockstep(kernel, mode):
    """phase0: Phase 0 backend; sound: proven-range pruning; profile: observed-range
    pruning with guards (a guard firing fails the test); aapcs: sound with the
    optional full AAPCS entry ABI (default is entry ABI "none") (only R0 is compared, as for every mode)."""
    import sys
    sys.path.insert(0, ROOT)
    from tools.backend.gba2gbc_core import build
    elf = os.path.join(BUILD, "kernels", kernel + ".elf")
    tag = "" if mode == "phase0" else "." + mode
    rom = os.path.join(BUILD, "roms", kernel + tag + ".gbc")
    prof = profile_for(elf) if mode == "profile" else None
    prune = {"phase0": None, "aapcs": "sound"}.get(mode, mode)
    opts = {"entry_abi": "aapcs"} if mode == "aapcs" else None
    build(elf, rom, asm_out=os.path.join(BUILD, "roms", kernel + tag + ".asm"),
          prune=prune, profile=prof, opts=opts)
    ref, gb = RefARM(elf), GB(rom)
    total = 0
    failures = []
    try:
        for s in seeds(kernel):
            exp = ref.run(s)
            got, cyc = gb.run(s)
            total += cyc
            if exp != got:
                failures.append((s, exp, got))
                if len(failures) >= 5:
                    break
    finally:
        gb.stop()
    with open(os.path.join(BUILD, "cycles.csv"), "a") as fh:
        fh.write(f"{kernel},{mode},{SEEDS},{total / SEEDS:.0f}\n")
    assert not failures, "mismatches (R0..R3, expected, got): " + "; ".join(
        f"{tuple(hex(v) for v in s)} {e:#010x} {g:#010x}" for s, e, g in failures)
