"""Generate runtime/hal_luts.inc: page-aligned ROM0 lookup tables of the spatial OAM
shim and the VCOUNT shim (docs/hal.md).

* X_gb = floor(x * 2 / 3) + 8 for the 9-bit GBA X (x >= 240 wraps to x - 512),
  stored as signed 16-bit (XLUT_LO / XLUT_HI, 512 entries each = 2 pages);
* Y_gb = floor(y * 9 / 10) + 16 for the 8-bit GBA Y (y >= 160 wraps to y - 256),
  signed 16-bit (YLUT_LO / YLUT_HI, 256 entries = 1 page each);
* VCOUNT_LUT[LY]: GB LY 0-153 -> GBA VCOUNT 0-227 (visible 0-143 -> 0-159,
  VBlank 144-153 -> 160-227)."""
import sys


def gb_x(x):
    xs = x - 512 if x >= 240 else x
    return (xs * 2) // 3 + 8


def gb_y(y):
    ys = y - 256 if y >= 160 else y
    return (ys * 9) // 10 + 16


def vcount(ly):
    return ly * 160 // 144 if ly < 144 else 160 + (ly - 144) * 68 // 10


def table(name, vals):
    out = [f"{name}::"]
    for i in range(0, len(vals), 16):
        out.append("    db " + ", ".join(f"${v & 0xFF:02X}" for v in vals[i:i + 16]))
    return out


def main():
    xs = [gb_x(x) for x in range(512)]
    ys = [gb_y(y) for y in range(256)]
    L = ["; Generated by tools/hal/make_luts.py — do not edit.",
         'SECTION "hal_luts", ROM0, ALIGN[8]']
    L += table("XLUT_LO", [v & 0xFF for v in xs]) + table("XLUT_HI", [(v >> 8) & 0xFF for v in xs])
    L += table("YLUT_LO", [v & 0xFF for v in ys]) + table("YLUT_HI", [(v >> 8) & 0xFF for v in ys])
    L += table("VCOUNT_LUT", [vcount(i) for i in range(154)] + [0] * 102)
    sys.stdout.write("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
