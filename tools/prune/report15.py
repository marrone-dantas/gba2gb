"""Phase 1.5 report: WRAM / HRAM / M-cycles / code bytes per kernel, cumulative per
item, vs Phase 0 and vs Phase 1 (writes docs/phase1_5_report.md).

Metrics (headless PyBoy, same seeds as the lockstep test):
  * M-cycles: mean per call (runtime timer);
  * WRAM touched: bytes of $C000-$DFFF written during a call (pattern fill, a few
    seeds; emulated ARM stack + SM83 return addresses);
  * WRAM peak: footprint = span of written bytes of the emulated ARM stack
    ($D800-$DFFF) + span of the SM83 native stack ($C000-$D7FF);
  * HRAM regs: static count of register-area bytes ($FF80-$FFBF) referenced by the
    generated code, plus the r0-r3 argument bytes and SP;
  * code bytes: size of the "kernel" ROM section.
Usage: python -m tools.prune.report15 [--seeds N] [--wram-seeds N]
"""
import argparse
import glob
import json
import os
import re
import subprocess
from tools.backend.gba2gbc_core import build
from tools.harness import RefARM, GB
from tools.profile.seeds import seeds
from tools.profile.range_tracer import trace_kernel

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
# (name, prune mode, opts) — cumulative; "phase1" is the Phase 1 B3 state
CONFIGS = [
    ("phase0", None, None),
    ("phase1", "sound", {"skip_lr": False}),
    ("+lr", "sound", {"skip_lr": True}),
    ("+entry", "sound", {"skip_lr": True, "entry_abi": "none"}),
]
REG_LO, REG_HI = 0xFF80, 0xFFC0


def hram_reg_bytes(asm_path):
    """Static count of register-area bytes ($FF80-$FFBF) the generated code reads or
    writes: explicit `ldh [$FFxx]` operands plus `[hl]` walks after `ld hl, $FFxx`
    (followed through inc l / dec l)."""
    used, cur = set(), None
    for line in open(asm_path):
        t = line.split(";")[0].strip()
        if not t:
            if line.strip().endswith(":"):
                cur = None
            continue
        m = re.match(r"ld hl, \$(FF[0-9A-F]{2})$", t)
        if m:
            cur = int(m.group(1), 16)
            continue
        if t in ("inc l",) and cur is not None:
            cur += 1
        elif t == "dec l" and cur is not None:
            cur -= 1
        elif t.startswith(("ld h,", "ld l,", "ld hl,", "call", "jp", "ret")) or "hl+" in t:
            cur = None
        if "[hl]" in t and cur is not None:
            used.add(cur)
        for m in re.finditer(r"\[\$(FF[0-9A-F]{2})\]", t):
            used.add(int(m.group(1), 16))
    used |= {0xFF80 + i for i in range(16)} | {0xFFB4 + i for i in range(4)}  # args + SP
    return len({a for a in used if REG_LO <= a < REG_HI})


def span(addrs, lo, hi):
    """Footprint of the written bytes inside [lo, hi): highest - lowest + 1."""
    a = [x for x in addrs if lo <= x < hi]
    return max(a) - min(a) + 1 if a else 0


def measure(kernel, nseeds, wseeds, configs):
    elf = os.path.join(ROOT, "build", "kernels", kernel + ".elf")
    prof = trace_kernel(elf, nseeds, os.path.join(ROOT, "build", "profiles", f"{kernel}.s{nseeds}.json"))
    ref = RefARM(elf)
    ss = seeds(kernel, nseeds)
    exp = [ref.run(s) for s in ss]
    out = {}
    for name, prune, opts in configs:
        rom = os.path.join(ROOT, "build", "report15", f"{kernel}.{name.strip('+')}.gbc")
        os.makedirs(os.path.dirname(rom), exist_ok=True)
        build(elf, rom, asm_out=rom[:-4] + ".asm", prune=prune, profile=prof if prune == "profile" else None, opts=opts)
        gb = GB(rom)
        cyc = ok = 0
        try:
            for s, e in zip(ss, exp):
                r0, c = gb.run(s)
                cyc += c
                ok += r0 == e
            wram = set()
            for s in ss[:wseeds]:
                wram |= gb.wram_touched(s)
        finally:
            gb.stop()
        mp = open(rom + ".map").read()
        code = int(re.search(r'\(\$([0-9a-f]+) bytes\) \["kernel"\]', mp).group(1), 16)
        out[name] = {"mcycles": cyc / len(ss), "ok": ok, "seeds": len(ss), "wram": len(wram),
                     "wram_peak": span(wram, 0xD800, 0xE000) + span(wram, 0xC000, 0xD800),
                     "hram": hram_reg_bytes(rom[:-4] + ".asm"), "code": code}
    return out


def pct(a, b):
    return f"{100 * (b - a) / a:+.0f}%" if a else "n/a"


def render(res, configs, nseeds, wseeds):
    names = [c[0] for c in configs]
    last = names[-1]
    L = ["# Phase 1.5 report — WRAM / HRAM gap", "",
         "Generated by `python -m tools.prune.report15` (do not edit by hand).", "",
         f"Seeds: {nseeds} per kernel for M-cycles and R0 checks, {wseeds} for WRAM. Columns are "
         "cumulative: " + ", ".join(f"**{n}**" for n in names) + ". `phase1` = Phase 1 sound pruning "
         "(state after B3); `+entry` is the opt-in entry ABI (see docs/frame_layout.md).", ""]
    tot = {n: {k: 0 for k in ("mcycles", "wram", "wram_peak", "hram", "code")} for n in names}
    for metric, title in (("wram", "WRAM bytes touched"), ("wram_peak", "WRAM peak footprint (bytes)"),
                          ("hram", "HRAM register bytes"), ("mcycles", "M-cycles per call"), ("code", "Code bytes")):
        L += [f"## {title}", "", "| kernel | " + " | ".join(names) + f" | Δ vs phase0 | Δ vs phase1 |",
              "|---|" + "---|" * (len(names) + 2)]
        for k, r in res.items():
            for n in names:
                tot[n][metric] += r[n][metric]
            L.append(f"| {k} | " + " | ".join(f"{r[n][metric]:.0f}" for n in names) +
                     f" | {pct(r['phase0'][metric], r[last][metric])} | {pct(r['phase1'][metric], r[last][metric])} |")
        L.append("| **total** | " + " | ".join(f"{tot[n][metric]:.0f}" for n in names) +
                 f" | {pct(tot['phase0'][metric], tot[last][metric])} | {pct(tot['phase1'][metric], tot[last][metric])} |")
        L.append("")
    bad = [(k, n) for k, r in res.items() for n in names if r[n]["ok"] != r[n]["seeds"]]
    L.append("R0 matched Unicorn for every seed in every configuration." if not bad else f"R0 MISMATCHES: {bad}")
    return "\n".join(L) + "\n", tot


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--seeds", type=int, default=1000)
    ap.add_argument("--wram-seeds", type=int, default=3)
    ap.add_argument("--out", default=os.path.join(ROOT, "docs", "phase1_5_report.md"))
    a = ap.parse_args(argv)
    subprocess.run(["make", "-s", "-C", os.path.join(ROOT, "tests", "kernels")], check=True)
    ks = sorted(os.path.basename(p)[:-4] for p in glob.glob(os.path.join(ROOT, "build", "kernels", "k*.elf")))
    from multiprocessing import Pool
    with Pool() as pool:
        rs = pool.starmap(measure, [(k, a.seeds, a.wram_seeds, CONFIGS) for k in ks])
    res = dict(zip(ks, rs))
    md, tot = render(res, CONFIGS, a.seeds, a.wram_seeds)
    json.dump(res, open(os.path.join(ROOT, "build", "phase1_5_report.json"), "w"), indent=1)
    open(a.out, "w").write(md)
    for n, t in tot.items():
        print(n, {k: round(v) for k, v in t.items()})


if __name__ == "__main__":
    main()
