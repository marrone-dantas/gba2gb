"""Phase 1 report: Phase 0 vs pruned code per kernel (writes docs/phase1_report.md).

For every kernel and backend mode it measures, on headless PyBoy:
  * M-cycles per call (runtime timer, mean over the seeds),
  * code bytes (size of the "kernel" ROM section) and static SM83 instruction count,
  * WRAM bytes touched (pattern fill of $C000-$DFFF, a few seeds),
  * register-file bytes needed (per ARM register, the widest storage of its SSA
    values: Phase 0 = 4 bytes for every register used),
and checks R0 against Unicorn for every seed.

Modes: phase0 | flags (narrowed backend, every value 32-bit) | sound | profile.
Usage: python -m tools.prune.report [--seeds N] [--wram-seeds N] [--out docs/phase1_report.md]
"""
import argparse
import glob
import json
import os
import re
import subprocess
from tools.backend.gba2gbc_core import build
from tools.harness import RefARM, GB
from tools.profile.seeds import seeds
from tools.profile.range_tracer import trace_kernel
from tools.prune import range_analysis as ra
from tools.prune.bitwidth_pruning import build_plan

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
MODES = ["phase0", "flags", "sound", "profile"]


def code_stats(rom):
    m = open(rom + ".map").read()
    size = int(re.search(r'\$[0-9a-f]+-\$[0-9a-f]+ \(\$([0-9a-f]+) bytes\) \["kernel"\]', m).group(1), 16)
    asm = open(rom[:-4] + ".asm").read().splitlines()
    n = sum(1 for l in asm if l.startswith("    ") and not l.strip().startswith(";"))
    return size, n


def reg_bytes(elf, mode, prof):
    plan = build_plan(elf, prof, "profile" if mode == "profile" else "sound")
    regs = {}
    for v in plan.ssa.values:
        if v.kind == "param":
            continue
        n = 4 if mode in ("phase0", "flags") else plan.store(v)[0]
        regs[v.reg] = max(regs.get(v.reg, 0), n)
    for r in range(4):  # arguments always arrive as 32-bit
        regs[r] = 4
    return sum(regs.values())


def measure(kernel, nseeds, wseeds):
    elf = os.path.join(ROOT, "build", "kernels", kernel + ".elf")
    ppath = os.path.join(ROOT, "build", "profiles", f"{kernel}.s{nseeds}.json")
    prof = trace_kernel(elf, nseeds, ppath)
    ref = RefARM(elf)
    ss = seeds(kernel, nseeds)
    exp = [ref.run(s) for s in ss]
    out = {}
    for mode in MODES:
        rom = os.path.join(ROOT, "build", "report", f"{kernel}.{mode}.gbc")
        os.makedirs(os.path.dirname(rom), exist_ok=True)
        build(elf, rom, asm_out=rom[:-4] + ".asm", prune=None if mode == "phase0" else mode,
              profile=prof if mode == "profile" else None)
        gb = GB(rom)
        cyc, ok = 0, 0
        try:
            for s, e in zip(ss, exp):
                r0, c = gb.run(s)
                cyc += c
                ok += r0 == e
            wram = set()
            for s in ss[:wseeds]:
                wram |= gb.wram_touched(s)
        finally:
            gb.stop()
        size, ninstr = code_stats(rom)
        out[mode] = {"mcycles": cyc / len(ss), "ok": ok, "seeds": len(ss), "code": size,
                     "instrs": ninstr, "wram": len(wram), "regbytes": reg_bytes(elf, mode, prof)}
    return out


def pct(a, b):
    return f"{100 * (b - a) / a:+.0f}%" if a else "n/a"


def render(res, nseeds, wseeds):
    L = ["# Phase 1 report — bit-width pruning vs Phase 0", "",
         "Generated by `python -m tools.prune.report` (do not edit by hand).", "",
         f"Seeds per kernel: {nseeds} for M-cycles/correctness (same seeds as the lockstep test), "
         f"{wseeds} for WRAM. M-cycles: mean per call measured with the runtime timer. "
         "Modes: **phase0** = Phase 0 backend; **flags** = narrowed backend with every value kept 32-bit "
         "(isolates the non-width gains: flag elision, constant shifts as byte moves, constant multiply "
         "as shift-and-add, bounded MUL loop); **sound** = proven-range narrowing (default); **profile** = "
         "observed-range narrowing with runtime guards.", "",
         "## M-cycles per call", "",
         "| kernel | phase0 | flags | sound | Δ sound | profile | Δ profile | R0 ok (sound/profile) |",
         "|---|---|---|---|---|---|---|---|"]
    tot = {m: 0 for m in MODES}
    red = {m: [] for m in MODES}
    for k, r in res.items():
        b = r["phase0"]["mcycles"]
        for m in MODES:
            tot[m] += r[m]["mcycles"]
            red[m].append((r[m]["mcycles"] - b) / b)
        L.append(f"| {k} | {b:.0f} | {r['flags']['mcycles']:.0f} | {r['sound']['mcycles']:.0f} | "
                 f"{pct(b, r['sound']['mcycles'])} | {r['profile']['mcycles']:.0f} | {pct(b, r['profile']['mcycles'])} | "
                 f"{r['sound']['ok']}/{r['profile']['ok']} of {r['sound']['seeds']} |")
    L.append(f"| **total** | {tot['phase0']:.0f} | {tot['flags']:.0f} | {tot['sound']:.0f} | "
             f"{pct(tot['phase0'], tot['sound'])} | {tot['profile']:.0f} | {pct(tot['phase0'], tot['profile'])} | |")
    mean = {m: 100 * sum(v) / len(v) for m, v in red.items()}
    L += ["", f"Mean per-kernel change: flags {mean['flags']:+.1f}%, sound {mean['sound']:+.1f}%, "
          f"profile {mean['profile']:+.1f}%. Total-cycle change (dominated by k19/k02): "
          f"flags {pct(tot['phase0'], tot['flags'])}, sound {pct(tot['phase0'], tot['sound'])}, "
          f"profile {pct(tot['phase0'], tot['profile'])}.", "",
          "## Code size and RAM", "",
          "| kernel | code B phase0 → sound | SM83 instrs phase0 → sound | WRAM B phase0 → sound | reg-file B phase0 → sound / profile |",
          "|---|---|---|---|---|"]
    t = {x: [0, 0] for x in ("code", "instrs", "wram", "regbytes")}
    for k, r in res.items():
        for x in t:
            t[x][0] += r["phase0"][x]
            t[x][1] += r["sound"][x]
        L.append(f"| {k} | {r['phase0']['code']} → {r['sound']['code']} ({pct(r['phase0']['code'], r['sound']['code'])}) | "
                 f"{r['phase0']['instrs']} → {r['sound']['instrs']} | {r['phase0']['wram']} → {r['sound']['wram']} | "
                 f"{r['phase0']['regbytes']} → {r['sound']['regbytes']} / {r['profile']['regbytes']} |")
    L.append(f"| **total** | {t['code'][0]} → {t['code'][1]} ({pct(*t['code'])}) | {t['instrs'][0]} → {t['instrs'][1]} "
             f"({pct(*t['instrs'])}) | {t['wram'][0]} → {t['wram'][1]} ({pct(*t['wram'])}) | "
             f"{t['regbytes'][0]} → {t['regbytes'][1]} ({pct(*t['regbytes'])}) |")
    L += ["", "WRAM = bytes of $C000-$DFFF written during a call (emulated ARM stack + native SM83 "
          "stack). Register-file bytes = HRAM bytes actually needed per ARM register (widest "
          "storage among its SSA values; arguments r0-r3 count as 4)."]
    return "\n".join(L) + "\n", mean, tot, t


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--seeds", type=int, default=1000)
    ap.add_argument("--wram-seeds", type=int, default=3)
    ap.add_argument("--out", default=os.path.join(ROOT, "docs", "phase1_report.md"))
    ap.add_argument("--kernels", nargs="*")
    a = ap.parse_args(argv)
    subprocess.run(["make", "-s", "-C", os.path.join(ROOT, "tests", "kernels")], check=True)
    ks = a.kernels or sorted(os.path.basename(p)[:-4] for p in glob.glob(os.path.join(ROOT, "build", "kernels", "k*.elf")))
    from multiprocessing import Pool
    with Pool() as pool:
        rs = pool.starmap(measure, [(k, a.seeds, a.wram_seeds) for k in ks])
    res = dict(zip(ks, rs))
    md, mean, tot, t = render(res, a.seeds, a.wram_seeds)
    json.dump(res, open(os.path.join(ROOT, "build", "phase1_report.json"), "w"), indent=1)
    open(a.out, "w").write(md)
    print(md)


if __name__ == "__main__":
    main()
