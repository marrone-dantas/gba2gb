"""Phase 5 A2: EWRAM object allocator for MBC5 SRAM paging (docs/sram_paging.md).

GBA EWRAM (0x02000000) is mapped onto the cartridge SRAM: 16 banks x 8 KiB
(128 KiB), bank = (addr >> 13) & 15, GB address = $A000 | (addr & $1FFF). The
mapping is the identity on offsets, so the allocator works at link time: it
decides the EWRAM address of every object (one input section `.ewram.<name>` per
object) so that

* objects of at most 8 KiB never straddle a bank boundary (an access to them needs
  one compile-time bank number, which the bank-switch pass can hoist), packed by
  first-fit decreasing into the 16 banks;
* larger objects start on a bank boundary and occupy consecutive banks (accesses
  to them select the bank at run time from the address);
* the total fits in 128 KiB.

It emits a GNU ld script fragment that places the sections at those offsets.

CLI (used by tests/demos/Makefile):
  python3 ewram_alloc.py OBJ.o --base gba.ld -o OUT.ld [--report OUT.json]
"""
from __future__ import annotations
import argparse
import json
import re
import subprocess

BANK = 0x2000
NBANKS = 16
EWRAM = 0x02000000


class AllocError(Exception):
    pass


def allocate(objects):
    """objects: [(name, size, align)] -> {name: (offset, size)} (offsets from 0x02000000)."""
    big = sorted([o for o in objects if o[1] > BANK], key=lambda o: -o[1])
    small = sorted([o for o in objects if o[1] <= BANK], key=lambda o: (-o[1], o[0]))
    place = {}
    used = [0] * NBANKS          # fill level of each bank
    b = 0
    for name, size, align in big:
        n = -(-size // BANK)
        if b + n > NBANKS:
            raise AllocError(f"EWRAM object {name} ({size} bytes) does not fit the 128 KiB of SRAM")
        place[name] = (b * BANK, size)
        used[b:b + n] = [BANK] * n
        used[b + n - 1] = size - (n - 1) * BANK
        b += n
    for name, size, align in small:
        for k in range(NBANKS):
            off = -(-used[k] // align) * align
            if off + size <= BANK:
                place[name] = (k * BANK + off, size)
                used[k] = off + size
                break
        else:
            raise AllocError(f"EWRAM object {name} ({size} bytes) does not fit any SRAM bank")
    return place


def banks_of(off, size):
    return list(range(off // BANK, (off + size - 1) // BANK + 1))


def ld_fragment(place):
    """Output-section statement placing the .ewram.<name> sections."""
    L = ["    /* generated by tools/sram/ewram_alloc.py - EWRAM objects -> MBC5 SRAM banks */",
         f"    .ewram {EWRAM:#x} (NOLOAD) : {{", "        __ewram_start = .;"]
    for name, (off, size) in sorted(place.items(), key=lambda kv: kv[1][0]):
        L.append(f"        . = {off:#x};  /* bank {off // BANK}, {size} bytes */")
        L.append(f"        KEEP(*(.ewram.{name}))")
    L += ["        __ewram_end = .;", "    }"]
    return "\n".join(L) + "\n"


def link_script(base, place):
    """The base GBA link script with the .ewram statement inserted before /DISCARD/."""
    with open(base) as fh:
        s = fh.read()
    i = s.index("    /DISCARD/")
    return s[:i] + ld_fragment(place) + s[i:]


def sections_of(obj):
    """[(name, size, align)] of the .ewram.<name> sections of an object file."""
    out = subprocess.run(["arm-none-eabi-objdump", "-h", obj], capture_output=True, text=True, check=True).stdout
    res = []
    for m in re.finditer(r"^\s*\d+\s+\.ewram\.(\S+)\s+([0-9a-f]+)\s+\S+\s+\S+\s+\S+\s+2\*\*(\d+)", out, re.M):
        res.append((m.group(1), int(m.group(2), 16), 1 << int(m.group(3))))
    return res


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("obj")
    ap.add_argument("-o", required=True)
    ap.add_argument("--base", required=True)
    ap.add_argument("--report")
    a = ap.parse_args()
    place = allocate(sections_of(a.obj))
    with open(a.o, "w") as fh:
        fh.write(link_script(a.base, place))
    if a.report:
        with open(a.report, "w") as fh:
            json.dump({n: {"offset": o, "size": s, "banks": banks_of(o, s)} for n, (o, s) in place.items()}, fh, indent=1)


if __name__ == "__main__":
    main()
