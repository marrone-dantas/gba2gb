"""Port profile for PICO-8 conversions built on the small "pico8.h" GBA platform layer
(spr / pal / camera / update_screen, e.g. JeffRuLz's Celeste Classic GBA).
docs/homebrew_port.md.

build_port(elf, out) bakes the game's 4bpp sprite sheet and font (ELF symbols, read
from the user's own build) into DMG 2bpp tiles and builds the GB ROM with:
  * overrides: spr/pal/camera/update_screen/CpuFastSet -> runtime/ports/pico8gba_dmg.asm;
  * the HAL in port mode: double-buffered port-owned OAM (PORT_OAM), only the displayed
    BG screen block reaches the GB map (PORT_BGMAP), BG maps readable through the
    SRAM VRAM shadow, ARM image copied to SRAM (images larger than 8 KiB).
No ROM bytes are stored in the repository; the baked include goes to a build directory.
"""
from __future__ import annotations
import os
from elftools.elf.elffile import ELFFile

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
PORT_ASM = os.path.join(ROOT, "runtime", "ports", "pico8gba_dmg.asm")
# PICO-8 palette (sRGB)
PICO8 = [(0, 0, 0), (29, 43, 83), (126, 37, 83), (0, 135, 81), (171, 82, 54), (95, 87, 79),
         (194, 195, 199), (255, 241, 232), (255, 0, 77), (255, 163, 0), (255, 236, 39),
         (0, 228, 54), (41, 173, 255), (131, 118, 156), (255, 119, 168), (255, 204, 170)]
OVERRIDES = {"spr": "p8_spr", "pal": "p8_pal", "camera": "p8_camera",
             "update_screen": "p8_update_screen", "CpuFastSet": "p8_cpufastset"}


def luma(c):
    r, g, b = c
    return 0.299 * r + 0.587 * g + 0.114 * b


def groups():
    """colour -> 2bpp index: 0 = colour 0 (transparent / backdrop), 1..3 = luminance
    terciles of colours 1-15 (dark .. light); index k is shown as shade 3-k."""
    order = sorted(range(1, 16), key=lambda c: luma(PICO8[c]))
    idx = [0] * 16
    for i, c in enumerate(order):
        idx[c] = 1 + i * 3 // 15
    return idx


def sym_bytes(elf_path, names):
    with open(elf_path, "rb") as fh:
        elf = ELFFile(fh)
        st = elf.get_section_by_name(".symtab")
        text = elf.get_section_by_name(".text")
        base, data = text["sh_addr"], text.data()
        out = {}
        want = {n: n for n in names}
        want.update({f"_ZL{len(n)}{n}": n for n in names})     # C++ internal linkage
        for s in st.iter_symbols():
            if s.name in want and s["st_size"]:
                o = s["st_value"] - base
                out[want[s.name]] = data[o:o + s["st_size"]]
    missing = set(names) - set(out)
    if missing:
        raise KeyError(f"symbols not found: {sorted(missing)}")
    return out


def tile_2bpp(t4, idx):
    out = bytearray()
    for row in range(8):
        lo = hi = 0
        for x in range(8):
            b = t4[row * 4 + x // 2]
            c = (b >> 4) if x & 1 else (b & 15)
            i = idx[c]
            lo |= (i & 1) << (7 - x)
            hi |= (i >> 1) << (7 - x)
        out += bytes((lo, hi))
    return bytes(out)


def bake(elf_path, gfx="GFX_DATA", font="FNT_DATA"):
    d = sym_bytes(elf_path, [gfx, font])
    idx = groups()
    ng = len(d[gfx]) // 32
    nf = min(len(d[font]) // 32, 256 - ng)
    tiles = [tile_2bpp(d[gfx][32 * t:32 * t + 32], idx) for t in range(ng)]
    tiles += [tile_2bpp(d[font][32 * t:32 * t + 32], idx) for t in range(nf)]
    # representative colour of each index: the most frequent sheet colour of that index
    cnt = [0] * 16
    for b in d[gfx]:
        cnt[b & 15] += 1
        cnt[b >> 4] += 1
    rep = [max((c for c in range(1, 16) if idx[c] == k), key=lambda c: cnt[c]) for k in (1, 2, 3)]
    shade = [3 - idx[c] for c in range(16)]
    shade[0] = 3
    return {"tiles": tiles, "font_base": ng, "rep": rep, "shade": shade, "idx": idx}


def write_inc(b, path):
    L = ["; generated by tools/ports/pico8gba.py - do not edit (baked from the user's build)",
         f"DEF P8_NOBJ EQU {len(b['tiles'])}", f"DEF P8_FONT_BASE EQU {b['font_base']}",
         'SECTION "p8_tiles", ROMX', "P8ObjTiles::"]
    blob = b"".join(b["tiles"])
    L += ["    db " + ", ".join(f"${x:02X}" for x in blob[i:i + 32]) for i in range(0, len(blob), 32)]
    L += ['SECTION "p8_tabs", ROM0', "P8Rep:: db " + ", ".join(map(str, b["rep"])),
          "P8ShadeTab:: db " + ", ".join(map(str, b["shade"]))]
    open(path, "w").write("\n".join(L) + "\n")


def port_config(inc_dir, display_bg=1, profile=False):
    return {"overrides": dict(OVERRIDES), "asm": [PORT_ASM], "inc": inc_dir,
            "defines": ["PORT_OAM", "PORT_BGMAP", "ROM_SRAM", "VRAM_SHADOW"] + (["PROFILE"] if profile else []),
            "rom_sram": True, "vram_shadow": True, "display_bg": display_bg, "port_init": True}


def build_port(elf, out, prune="sound", display_bg=1, profile=False, **kw):
    from tools.backend.gba2gbc_core import build
    bdir = os.path.dirname(os.path.abspath(out))
    b = bake(elf)
    write_inc(b, os.path.join(bdir, "p8_tiles.inc"))
    return build(elf, out, entry="main", hal=True, prune=prune, port=port_config(bdir, display_bg, profile), **kw)
